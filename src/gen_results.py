"""Scan all committed track outputs and emit a single consolidated RESULTS.md.

Aggregates per-track: data summary, RQ-H (joint vs decoupled), RQ-A1, learned-router
baseline, phase-diagram sweep, and the extended 9-config frontier. Run:
    python src/gen_results.py
"""
from __future__ import annotations

import glob
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "outputs"

NAMES = {
    "trackA": "Track A - TartanDrive off-road (full 1198 frames)",
    "trackA_309": "Track A - TartanDrive off-road (309-frame segment)",
    "trackC": "Track C - WoodScape Soiling, fisheye (lens contamination)",
    "trackD_rain_2_0": "Track D - RADIATE rain 2-0",
    "trackD_rain_3_0": "Track D - RADIATE rain 3-0",
    "trackD_rain_4_0": "Track D - RADIATE rain 4-0 (real adverse weather)",
    "trackD_snow_1_0": "Track D - RADIATE snow",
    "trackD_fog_6_0": "Track D - RADIATE fog 6-0",
    "trackD_fog_8_0": "Track D - RADIATE fog 8-0",
    "trackD_fog_8_1": "Track D - RADIATE fog 8-1",
    "trackD_night_1_0": "Track D - RADIATE night",
}
ORDER = ["trackD_fog_6_0", "trackD_fog_8_0", "trackD_fog_8_1", "trackD_night_1_0",
         "trackD_rain_2_0", "trackD_rain_3_0", "trackD_rain_4_0", "trackD_snow_1_0",
         "trackC", "trackA", "trackA_309"]


def jload(p):
    try:
        return json.load(open(p))
    except Exception:
        return None


def deadline_ms(t):
    s = jload(OUT / t / "phase3" / "phase3_summary.json")
    return s.get("deadline_ms") if s else None


def main():
    tracks = [t for t in ORDER if (OUT / t / "phase1" / "phase1_summary.json").exists()]
    L = ["# Consolidated Results", "",
         "Auto-generated by `src/gen_results.py` from the committed per-track outputs.",
         "Latencies are environment-specific (Apple M5 MPS / dev GPUs), not reportable in",
         "absolute terms; the cross-method comparisons are the results. CIs are 95% over 5",
         "seeds. The coupling in the coupled regime is a designed modeling assumption; the",
         "uncoupled regime is the control. Pseudo-GT = agreement with the C1 reference.", ""]

    # 1. Data summary
    L += ["## 1. Track / data summary", "",
          "| track | frames | fault % | contention p95x | coupled r | uncoupled r | deadline (ms) |",
          "|---|---|---|---|---|---|---|"]
    for t in tracks:
        p1 = jload(OUT / t / "phase1" / "phase1_summary.json")
        ff = p1.get("trackA_fault_frac", p1.get("fault_frac"))
        c = p1.get("contention", {}).get("p95_shift_ratio")
        reg = p1.get("regimes", {})
        dl = deadline_ms(t)
        L.append(f"| {NAMES.get(t,t)} | {p1.get('n_frames','?')} | "
                 f"{ff*100:.1f}% | {c:.2f}x | {reg.get('coupled',{}).get('pearson_r',float('nan')):.2f} | "
                 f"{reg.get('uncoupled',{}).get('pearson_r',float('nan')):.2f} | "
                 f"{dl:.0f} |" if ff is not None and c and dl else f"| {NAMES.get(t,t)} | ... |")

    # 2. RQ-H
    L += ["", "## 2. RQ-H (headline): joint vs decoupled deadline-miss",
          "Reduction = decoupled minus joint (positive = coupling helps). Control = uncoupled regime.", "",
          "| track | kappa | joint miss | decoupled miss | reduction (95% CI) | sig | uncoupled |",
          "|---|---|---|---|---|---|---|"]
    for t in tracks:
        s = jload(OUT / t / "phase5" / "phase5_rqh.json")
        if not s:
            continue
        su = s["summary"]; d = su["coupled"]; df = d["miss_reduction_decoupled_minus_joint"]
        u = su["uncoupled"]["miss_reduction_decoupled_minus_joint"]
        L.append(f"| {NAMES.get(t,t)} | {d['kappa_mean']:.2f} | {d['joint_miss']['mean']:.3f} | "
                 f"{d['decoupled_miss']['mean']:.3f} | {df['mean']*100:+.2f}pp "
                 f"[{df['lo']*100:.2f},{df['hi']*100:.2f}] | {'YES' if df['significant'] else 'no'} | "
                 f"{u['mean']*100:+.2f}pp |")

    # 3. RQ-A1
    L += ["", "## 3. RQ-A1: persistence (belief) vs memoryless switching, matched accuracy", "",
          "| track | belief switch | memoryless switch | verdict |", "|---|---|---|---|"]
    for t in tracks:
        a = jload(OUT / t / "phase6" / "phase6_results.json")
        if not a:
            continue
        a1 = a["rq_a1"]
        L.append(f"| {NAMES.get(t,t)} | {a1['belief']['mean']:.3f} | {a1['memoryless']['mean']:.3f} | "
                 f"{a1['verdict'].split(':')[0]} |")

    # 4. Learned router
    L += ["", "## 4. Learned routing baseline: joint vs learned MLP (same belief features)",
          "Both use the same features + matched hysteresis; MLP trained on oracle labels (sequence split).", "",
          "| track | joint miss | learned miss | learned-minus-joint (95% CI) | result |",
          "|---|---|---|---|---|"]
    for t in tracks:
        r = jload(OUT / t / "extras" / "learned_router.json")
        if not r:
            continue
        d = r["learned_minus_joint_miss"]
        L.append(f"| {NAMES.get(t,t)} | {r['joint_miss']['mean']:.3f} | {r['learned_miss']['mean']:.3f} | "
                 f"{d['mean']*100:+.2f}pp [{d['lo']*100:.2f},{d['hi']*100:.2f}] | {r['verdict'].split(':')[0]} |")

    # 5. Phase diagram
    L += ["", "## 5. RQ-H phase diagram (coupling-strength x onset-rate sweep)",
          "Significant-positive cells out of 20, and peak joint-vs-decoupled reduction. Coupling=0 row is the control (0).", "",
          "| track | sig+ cells | peak reduction |", "|---|---|---|"]
    for t in tracks:
        d = jload(OUT / t / "extras" / "phase_diagram.json")
        if not d:
            continue
        sig = sum(1 for c in d["cells"] if c["significant"] and c["miss_reduction"] > 0)
        peak = max(c["miss_reduction"] for c in d["cells"])
        L.append(f"| {NAMES.get(t,t)} | {sig}/{len(d['cells'])} | {peak*100:.1f}pp |")

    # 6. Extended frontier
    ext = sorted(glob.glob(str(OUT / "*_extended" / "phase3" / "frontier_table.csv")))
    if ext:
        L += ["", "## 6. Extended dense 9-config frontier"]
        for e in ext:
            tname = Path(e).parts[-3].replace("_extended", "")
            df = pd.read_csv(e)
            L += [f"", f"**{NAMES.get(tname, tname)}** (dense Pareto set):", "",
                  "| config | model | imgsz | accuracy | nom latency (ms) | meets deadline (contended) |",
                  "|---|---|---|---|---|---|"]
            for _, r in df.iterrows():
                L.append(f"| {r['config']} | {r['model']} | {int(r['imgsz'])} | {r['acc_overall']:.2f} | "
                         f"{r['lat_median_nom_ms']:.1f} | {r['meets_deadline_con']} |")

    # 7. Robustness: threshold rule, on-time utility, bootstrap
    rob = {t: jload(OUT / t / "extras" / "robustness.json") for t in tracks}
    rob = {t: r for t, r in rob.items() if r}
    if rob:
        L += ["", "## 7. Robustness: threshold rule, on-time utility, temporal bootstrap",
              "Same draws as RQ-H. Threshold rule = hard union `max(b_c,1[b_f>0.5])`; utility",
              "`U=mean a_t*1[lat<=D]` (late frame scores 0); bootstrap = moving-block (50, B=2000),",
              "pooled across seeds, of the per-frame miss reduction.", "",
              "| track | decoup miss | threshold miss | joint miss | joint-vs-threshold (95% CI) | U joint | U decoup | dU joint-decoup (95% CI) | bootstrap miss-reduction (95% CI) |",
              "|---|---|---|---|---|---|---|---|---|"]
        for t in tracks:
            r = rob.get(t)
            if not r:
                continue
            m = r["miss"]; u = r["utility"]
            jt = r["joint_minus_threshold_miss"]; du = r["utility_joint_minus_decoupled"]
            b = r["bootstrap_miss_reduction"]
            L.append(f"| {NAMES.get(t,t)} | {m['decoupled']['mean']:.3f} | {m['threshold']['mean']:.3f} | "
                     f"{m['joint']['mean']:.3f} | {jt['mean']*100:+.2f}pp [{jt['lo']*100:.2f},{jt['hi']*100:.2f}]"
                     f"{'*' if jt['significant'] else ''} | {u['joint']['mean']:.3f} | {u['decoupled']['mean']:.3f} | "
                     f"{du['mean']*100:+.2f}pp [{du['lo']*100:.2f},{du['hi']*100:.2f}]{'*' if du['significant'] else ''} | "
                     f"{b['mean_pp']:+.2f}pp [{b['lo_pp']:.2f},{b['hi_pp']:.2f}] |")
        # deadline-strictness sweep (every condition, multiplier x self-calibrated deadline)
        dl_tracks = [t for t in tracks if rob.get(t) and "deadline_sweep" in rob[t]]
        if dl_tracks:
            L += ["", "### 7b. Deadline-strictness sweep (ALL conditions)",
                  "Joint-vs-decoupled reduction (pp) at multiples of each track's self-calibrated deadline.", "",
                  "| track | 0.8x | 0.9x | 1.0x | 1.1x | 1.2x |", "|---|---|---|---|---|---|"]
            for t in dl_tracks:
                cells = {s["mult"]: s for s in rob[t]["deadline_sweep"]}
                row = " | ".join(f"{cells[m]['reduction_pp']:+.2f}{'*' if cells[m]['significant'] else ''}"
                                 for m in (0.8, 0.9, 1.0, 1.1, 1.2))
                L.append(f"| {NAMES.get(t,t)} | {row} |")
            L += ["", "### 7c. Externally-motivated fixed deadlines (not self-calibrated)",
                  "Joint-vs-decoupled reduction (pp) at a fixed perception budget.", "",
                  "| track | 10 Hz (100 ms) | 5 Hz (200 ms) |", "|---|---|---|"]
            for t in dl_tracks:
                fx = {s["hz"]: s for s in rob[t].get("fixed_deadline", [])}
                if 10.0 in fx and 5.0 in fx:
                    L.append(f"| {NAMES.get(t,t)} | {fx[10.0]['reduction_pp']:+.2f}"
                             f"{'*' if fx[10.0]['significant'] else ''} | {fx[5.0]['reduction_pp']:+.2f}"
                             f"{'*' if fx[5.0]['significant'] else ''} |")
            L += ["", "### 7d. Temporally-separated calibration (leakage / circularity check)",
                  "kappa fit on the first half of the trace; RQ-H evaluated on the held-out second half.",
                  "kappa is a structural regime constant, so it should be stable; the held-out test is only",
                  "informative where the held-out window actually contains faults.", "",
                  "| track | kappa full | kappa (1st half) | calib fault % | test fault % | held-out reduction (95% CI) |",
                  "|---|---|---|---|---|---|"]
            for t in dl_tracks:
                c = rob[t].get("calibration_split")
                if not c:
                    continue
                L.append(f"| {NAMES.get(t,t)} | {c['kappa_full']:.2f} | {c['kappa_split_firsthalf_mean']:.2f} | "
                         f"{c['calib_window_fault_frac']*100:.1f}% | {c['test_window_fault_frac']*100:.1f}% | "
                         f"{c['heldout_reduction_pp']:+.2f}pp [{c['lo_pp']:.2f},{c['hi_pp']:.2f}]"
                         f"{'*' if c['significant'] else ''} |")
        # fog kappa sweep
        fog = rob.get("trackD_fog_6_0")
        if fog and "kappa_sweep" in fog:
            L += ["", "### 7e. RADIATE fog kappa sweep (kappa=0 collapses to decoupled)", "",
                  "| kappa | reduction (95% CI) |", "|---|---|"]
            for s in fog["kappa_sweep"]:
                L.append(f"| {s['kappa']} | {s['reduction_pp']:+.2f}pp [{s['lo_pp']:.2f},{s['hi_pp']:.2f}]"
                         f"{'*' if s['significant'] else ''} |")
        ns_tracks = [t for t in tracks if rob.get(t) and "noise_sweep_joint_minus_threshold" in rob[t]]
        if ns_tracks:
            L += ["", "**Observation-noise sweep** (joint-vs-threshold deadline-miss gap; tests whether "
                  "soft fusion gains an edge under heavier sensor noise):", "",
                  "| track | sigma=0.15 | 0.30 | 0.50 | 0.75 |", "|---|---|---|---|---|"]
            for t in ns_tracks:
                cells = {s["sigma"]: s for s in rob[t]["noise_sweep_joint_minus_threshold"]}
                row = " | ".join(f"{cells[sg]['joint_minus_threshold_pp']:+.2f}pp"
                                 f"{'*' if cells[sg]['significant'] else ''}" for sg in (0.15, 0.30, 0.50, 0.75))
                L.append(f"| {NAMES.get(t,t)} | {row} |")

    # 8. Real-coupling measurement (Experiment A) + cross-sequence aggregation (Experiment B)
    rcs = {t: jload(OUT / t / "extras" / "real_coupling.json") for t in tracks}
    rcs = {t: r for t, r in rcs.items() if r}
    if rcs:
        L += ["", "## 8. Measured real fault-load coupling (Experiment A)",
              "Pc(F)/Pc(N) = P(high real load | fault/nominal), measured from C1 over the real frames",
              "(paper's coupled regime imposes 0.85/0.05). De-circ = RQ-H with contention driven by",
              "the REAL load signal instead of the fault labels (empirical kappa).", "",
              "| track | proxy | Pc(F) | Pc(N) | corr (95% CI) | de-circ reduction (95% CI) | verdict |",
              "|---|---|---|---|---|---|---|"]
        for t in tracks:
            r = rcs.get(t)
            if not r:
                continue
            ci = r.get("corr_ci", [float("nan"), float("nan")])
            L.append(f"| {NAMES.get(t,t)} | {r['load_proxy']} | {r['measured_Pc_fault']:.3f} | "
                     f"{r['measured_Pc_nominal']:.3f} | {r['corr_fault_load']:+.3f} "
                     f"[{ci[0]:+.3f},{ci[1]:+.3f}] | {r['decirc_reduction_pp']:+.2f}pp "
                     f"[{r['decirc_lo_pp']:.2f},{r['decirc_hi_pp']:.2f}] | "
                     f"{'coupled' if r['measured_Pc_fault'] > r['measured_Pc_nominal'] and r['decirc_significant'] else 'null'} |")
    mt = sorted(glob.glob(str(OUT / "multitrace" / "*.json")))
    # only per-condition aggregation files (skip predicted_vs_observed, bh_correction, etc.)
    mt = [m for m in mt if jload(m) and "per_sequence_reduction_pp" in (jload(m) or {})]
    if mt:
        L += ["", "## 9. Cross-sequence aggregation (Experiment B)",
              "CI over TRAJECTORIES (independent sequences), not seeds.", "",
              "| condition | n seq | per-seq reductions (pp) | mean | t-CI | cluster bootstrap | sign test |",
              "|---|---|---|---|---|---|---|"]
        for m in mt:
            d = jload(m)
            if not d:
                continue
            st = d.get("pooled_sign_test")
            stx = f"{st['positives']}/{st['n_nonzero']} +, p={st['p_one_sided']:.4f}" if st else "-"
            reds = ", ".join(f"{x:+.1f}" for x in d["per_sequence_reduction_pp"])
            L.append(f"| {d['condition']} | {d['n_sequences']} | {reds} | "
                     f"{d['cross_sequence_mean_pp']:+.2f} | "
                     f"[{d['t_interval_pp'][0]:.2f},{d['t_interval_pp'][1]:.2f}] | "
                     f"[{d['cluster_bootstrap_ci_pp'][0]:.2f},{d['cluster_bootstrap_ci_pp'][1]:.2f}] | {stx} |")
    pvo = jload(OUT / "multitrace" / "predicted_vs_observed.json")
    if pvo:
        L += ["", "## 10. Phase diagram as predictor (zero-point validation)",
              "The phase diagram predicts benefit ~0 at coupling ~0: confirmed by every uncoupled",
              "control and by the measured real-load points (Experiment A nulls). Sign correct at",
              "the imposed points; magnitudes under-predicted where faults are severe (severity is",
              f"not a grid axis) -- Pearson r={pvo['pearson_r']:.2f}, MAE={pvo['mae_pp']:.1f}pp.",
              "See `outputs/multitrace/predicted_vs_observed.png`."]

    # 11. Cross-sequence transfer of the FULL belief model (HMM + kappa)
    xfer = sorted(glob.glob(str(OUT / "*" / "extras" / "cross_seq_calib_from_*.json")))
    rows_x = []
    for x in xfer:
        d = jload(x)
        if not d or "rqh_reduction_full_transfer_pp" not in d:
            continue  # skip any legacy kappa-only files
        rows_x.append(d)
    if rows_x:
        n_sig = sum(1 for d in rows_x if d["rqh_reduction_full_transfer_pp"]["significant"])
        L += ["", "## 11. Cross-sequence transfer of the full belief model (HMM + kappa)",
              "Fit the fault-belief HMM + kappa on the CALIB sequence, evaluate on the held-out TEST",
              f"sequence. {n_sig}/{len(rows_x)} transfers keep RQ-H significant; all positive.", "",
              "| calib -> test | kappa xfer | fault bAcc native/xfer | RQ-H native | RQ-H full transfer |",
              "|---|---|---|---|---|"]
        for d in rows_x:
            c = Path(d["calib_track"]).name.replace("trackD_", "").replace("track", "")
            t = Path(d["test_track"]).name.replace("trackD_", "").replace("track", "")
            nat = d["rqh_reduction_native_pp"]; ful = d["rqh_reduction_full_transfer_pp"]
            L.append(f"| {c} -> {t} | {d['kappa_transferred_from_calib_track']:.2f} | "
                     f"{d['fault_bacc_native_hmm_on_test']:.2f} / {d['fault_bacc_transferred_hmm_on_test']:.2f} | "
                     f"{nat['mean']:+.2f}pp{'*' if nat['significant'] else ''} | "
                     f"{ful['mean']:+.2f}pp [{ful['lo']:.2f},{ful['hi']:.2f}]{'*' if ful['significant'] else ''} |")

    # 12. Deadline sweep of all policies (reviewer #3: scope to the tight-deadline band)
    dsw = sorted(glob.glob(str(OUT / "*" / "extras" / "oracle_deadline_sweep.json")))
    rows_d = [jload(x) for x in dsw]
    rows_d = [d for d in rows_d if d]
    if rows_d:
        L += ["", "## 12. Deadline sweep: coupling benefit is confined to the tight-deadline band",
              "Joint-vs-decoupled reduction (pp) at multiples of each track's self-calibrated (median-C1)",
              "deadline. The benefit peaks at 1.0x and collapses as the deadline loosens; oracle and",
              "reactive miss also shown at 1.0x (oracle is accuracy-greedy, so NOT a miss upper bound).", "",
              "| track | 0.8x | 0.9x | 1.0x | 1.1x | 1.2x | 1.5x | oracle@1.0 | reactive@1.0 |",
              "|---|---|---|---|---|---|---|---|---|"]
        for d in rows_d:
            r = {row["mult"]: row for row in d["rows"]}
            t = Path(d["track"]).name
            def red(m): return f"{r[m]['coupling_reduction_pp']:+.2f}{'*' if r[m]['coupling_sig'] else ''}" if m in r else "-"
            om = r[1.0]["oracle_miss"] if 1.0 in r else float("nan")
            rm = r[1.0]["reactive_miss"] if 1.0 in r else float("nan")
            L.append(f"| {t} | {red(0.8)} | {red(0.9)} | {red(1.0)} | {red(1.1)} | {red(1.2)} | {red(1.5)} | "
                     f"{om:.3f} | {rm:.3f} |")

    L += ["", "## Figures (committed under each track's outputs)",
          "- RQ-H per track: `outputs/<track>/phase5/rqh_centerpiece.png`",
          "- RQ-A1 / RQ-A2: `outputs/<track>/phase6/`",
          "- frontier: `outputs/<track>/phase3/frontier.png`",
          "- learned router / phase diagram: `outputs/<track>/extras/`",
          "", "See `REPORT.md` for per-phase verdicts and `WRITEUP.md` for the narrative + limitations.", ""]

    (ROOT / "RESULTS.md").write_text("\n".join(L), encoding="utf-8")
    print(f"wrote RESULTS.md ({len(tracks)} tracks)")


if __name__ == "__main__":
    raise SystemExit(main())
